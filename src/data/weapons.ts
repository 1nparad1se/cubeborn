export function baseWeapons(): WeaponDef[] {
  return WEAPONS.filter((w) => !w.evolved);
}

export function evolutionOf(id: string): WeaponDef | undefined {
  const w = WEAPON_BY_ID[id];
  return w?.evolution ? WEAPON_BY_ID[w.evolution.into] : undefined;
}
