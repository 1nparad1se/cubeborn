// Dev-only turnaround of a bestiary creature: ?mob=mob_spider&w=1600&h=1600&t=0
import * as THREE from 'three';
import { MOB_DEFS } from '../../src/models/mobs';
import { MobRig } from '../../src/render/rig/MobRig';
import { makeHeroTexture } from '../../src/render/Textures';

const q = new URLSearchParams(location.search);
const id = q.get('mob') ?? 'mob_spider';
const W = Number(q.get('w') ?? 1600);
const H = Number(q.get('h') ?? 1600);
const t = Number(q.get('t') ?? 0);
const gl = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
gl.setSize(W, H);
gl.outputColorSpace = THREE.SRGBColorSpace;
gl.setScissorTest(true);
document.body.appendChild(gl.domElement);
const tex = makeHeroTexture();
const views = [0.35, Math.PI - 0.2, -0.95, 0.95];
const def = MOB_DEFS[id];
views.forEach((yaw, i) => {
  const scene = new THREE.Scene();
  scene.background = new THREE.Color(0x1d1e24);
  scene.add(new THREE.HemisphereLight(0xe4ecff, 0x3a3444, 1.5));
  const key = new THREE.DirectionalLight(0xfff0dc, 2.4);
  key.position.set(3, 8, 5);
  scene.add(key);
  const rim = new THREE.DirectionalLight(0xffa080, 1.0);
  rim.position.set(-2, 4, -6);
  scene.add(rim);
  const rig = new MobRig(def, tex);
  rig.update(t);
  rig.root.rotation.y = yaw;
  scene.add(rig.root);
  rig.root.updateMatrixWorld(true);
  const bb = new THREE.Box3().setFromObject(rig.root);
  const c = bb.getCenter(new THREE.Vector3());
  const sz = bb.getSize(new THREE.Vector3());
  const r = Math.max(sz.x, sz.y, sz.z) * 0.62;
  const cam = new THREE.PerspectiveCamera(28, 1, 0.05, 100);
  const dist = r / Math.tan((14 * Math.PI) / 180);
  cam.position.set(c.x, c.y + dist * 0.25, c.z + dist);
  cam.lookAt(c);
  const cw = W / 2;
  const ch = H / 2;
  const x = (i % 2) * cw;
  const y = H - ch - Math.floor(i / 2) * ch;
  gl.setViewport(x, y, cw, ch);
  gl.setScissor(x, y, cw, ch);
  gl.render(scene, cam);
});
(window as unknown as { __done: boolean }).__done = true;
